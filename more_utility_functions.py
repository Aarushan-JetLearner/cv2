import cv2
import os
import numpy as np
img=cv2.imread(r"C:\Users\User\OneDrive\open cv\open cv images\image1.jpg")
resized_img=cv2.resize(img,(500,500))
cv2.imshow("image1",resized_img)
img2=cv2.imread(r"C:\Users\User\OneDrive\open cv\open cv images\image2.jpg")
resized_img2=cv2.resize(img2,(500,500))
cv2.imshow("image2",resized_img2)
combine_images=cv2.addWeighted(resized_img,0.9,resized_img2,0.9,0)
cv2.imshow("combined images",combine_images)
subtract_images=cv2.subtract(resized_img,resized_img2)
cv2.imshow("subtracted images",subtract_images)
kernel=np.ones([3,3],np.uint8)
print(kernel)
store=cv2.erode(resized_img,kernel)
cv2.imshow("new image",store)
gaussian_blur=cv2.GaussianBlur(resized_img,[3,3],0)
cv2.imshow("gaussian blur",gaussian_blur)
bilateral_blur=cv2.bilateralFilter(resized_img,8,65,75)
cv2.imshow("bilateral blur",bilateral_blur)
median_blur=cv2.medianBlur(resized_img,3)
cv2.imshow("median blur",median_blur)
border=cv2.copyMakeBorder(resized_img,10,10,10,10,cv2.BORDER_CONSTANT,value=(0,0,0))
cv2.imshow("border",border)
border2=cv2.copyMakeBorder(resized_img2,10,10,10,10,cv2.BORDER_REFLECT)
cv2.imshow("border2",border2)
cv2.waitKey(0)